package com.finagent.scope;

/**
 * 三种作用域模式（设计文档 D1 / D2）。
 *
 * <p>为什么只有三种而不是「选文档 + 附加筛选」的组合：组合会让「份数上限 5」这类规则
 * 失去依据 —— 用户先选 3 份再叠加行业筛选，解析出来的到底算 A 还是 B？
 * 三种模式各自有明确的份数特征，配额、提示、路由阈值都能分开定。
 */
public enum ScopeKind {

    /** A：用户直接选中若干份文档（软上限 5 份，超过只提示切 B）。 */
    DOCUMENTS,

    /** B：按公司 / 年份 / 报告类型 / 行业筛选，解析后仍落到一组具体文档。 */
    FILTER,

    /** C：全库检索（默认模式）。 */
    CORPUS
}
